import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, '..');
const catalogOutput = path.join(projectRoot, 'src/sections/router-management/components/icon-catalog.generated.ts');
const collections = ['solar', 'eva', 'mingcute', 'ant-design', 'iconamoon'];

const iconNames = new Set();

for (const collection of collections) {
  const sourcePath = path.join(projectRoot, 'node_modules', '@iconify-json', collection, 'icons.json');
  const source = JSON.parse(await readFile(sourcePath, 'utf8'));
  const names = [...Object.keys(source.icons ?? {}), ...Object.keys(source.aliases ?? {})];
  names.forEach((name) => iconNames.add(`${source.prefix}:${name}`));
}

const sortedNames = [...iconNames].sort((left, right) => left.localeCompare(right));
const generatedSource = `// Generated by scripts/generate-icon-catalog.mjs. Do not edit manually.\nexport const ICON_NAMES = ${JSON.stringify(sortedNames)} as const;\n`;

await writeFile(catalogOutput, generatedSource, 'utf8');
console.log(`Generated ${sortedNames.length} icon names in ${path.relative(projectRoot, catalogOutput)}`);
